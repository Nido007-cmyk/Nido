describe("C-01 · coronación sobre FTS5 real (corpus mínimo solo)", () => {
  let db: DatabaseSync;
  beforeAll(() => {
    db = new DatabaseSync(":memory:");
    db.exec("CREATE VIRTUAL TABLE chunks_fts USING fts5(chunk_id UNINDEXED, title, body)");
    const insert = db.prepare("INSERT INTO chunks_fts (chunk_id, title, body) VALUES (?, ?, ?)");
    docs.forEach((d, i) => insert.run(String(i), d.title, d.body));
  });
  type Row = { chunk_id: string; title: string; body: string; rank: number };
  const searchRaw = (query: string): Row[] => {
    const q = buildLexicalQuery(query);
    if (!q) return [];
    return db
      .prepare("SELECT chunk_id, title, body, bm25(chunks_fts) AS rank FROM chunks_fts WHERE chunks_fts MATCH ? ORDER BY rank LIMIT ?")
      .all(q.match, 48) as Row[];
  };
  const search = (query: string): Row[] => {
    const q = buildLexicalQuery(query);
    if (!q) return [];
    return filterByTermCoverage(searchRaw(query), q.terms);
  };

  it("W4-pt: «Austrália» corona con «Camberra» en el cuerpo", () => {
    const hits = search("Qual é a capital da Austrália?");
    expect(hits[0]?.title).toBe("Austrália");
    expect(hits[0]?.body).toContain("Camberra");
  });

  it("W3-en (desviación B-1 fijada): corona «Austrália»; el «Australia» inglés está en el top-3", () => {
    const hits = search("What is the capital of Australia?");
    expect(hits[0]?.title).toBe("Austrália");
    expect(hits[0]?.body).toContain("Camberra");
    expect(hits.slice(0, 3).map((h) => h.title)).toContain("Australia");
  });

  it("W3-es (desviación B-1 fijada): corona «Austrália»; «Australia» es el nº 2", () => {
    const hits = search("¿Cuál es la capital de Australia?");
    expect(hits[0]?.title).toBe("Austrália");
    expect(hits[0]?.body).toContain("Camberra");
    expect(hits[1]?.title).toBe("Australia");
  });

  it("W1-es (desviación B-2 fijada): en crudo mandan los documentos correctos; la puerta corona a Mozart", () => {
    const raw = searchRaw("¿Quién escribió el Quijote, según el corpus?");
    expect(raw.slice(0, 3).map((h) => h.title)).toEqual([
      "Wolfgang Amadeus Mozart",
      "Don Quijote de la Mancha",
      "Miguel de Cervantes",
    ]);
    const hits = search("¿Quién escribió el Quijote, según el corpus?");
    expect(hits.map((h) => h.title)).toEqual(["Wolfgang Amadeus Mozart"]);
  });

  it("W2-en (desviación B-2 fijada): en crudo mandan los correctos; la puerta deja la pregunta sin fuentes", () => {
    const raw = searchRaw("Who wrote Don Quixote, according to the corpus?");
    expect(raw.slice(0, 3).map((h) => h.title)).toEqual(["Don Quixote", "Miguel de Cervantes", "Dom Quixote"]);
    expect(search("Who wrote Don Quixote, according to the corpus?")).toEqual([]);
  });

  it("W1-pt (desviación B-2 fijada): en crudo mandan los correctos; la puerta deja la pregunta sin fuentes", () => {
    const raw = searchRaw("Quem escreveu Dom Quixote, segundo o corpus?");
    expect(raw.slice(0, 3).map((h) => h.title)).toEqual(["Dom Quixote", "Miguel de Cervantes", "William Shakespeare"]);
    expect(search("Quem escreveu Dom Quixote, segundo o corpus?")).toEqual([]);
  });

  it("muestra por categorías: 13/14 al top-1 (falla nombrada: la capital de Japón en portugués)", () => {
    const SAMPLE: Array<{ q: string; want: string[] }> = [
      { q: "¿Cuál es la capital de Japón?", want: ["Japón"] },
      { q: "¿Qué es la fiebre?", want: ["Fiebre"] },
      { q: "¿Qué es la diabetes?", want: ["Diabetes mellitus"] },
      { q: "O que é a diabetes?", want: ["Diabetes mellitus"] },
      { q: "¿Qué es la fotosíntesis?", want: ["Fotosíntesis"] },
      { q: "¿Cuándo fue la Segunda Guerra Mundial?", want: ["Segunda Guerra Mundial"] },
      { q: "When was World War II?", want: ["World War II"] },
      { q: "O que é um tsunami?", want: ["Tsunâmi"] },
      { q: "¿Quién fue Albert Einstein?", want: ["Albert Einstein"] },
      { q: "O que é o milho?", want: ["Milho"] },
      { q: "What is the Moon?", want: ["Moon"] },
      { q: "¿Qué es el río Amazonas?", want: ["Rio Amazonas"] },
      { q: "¿Qué es un tiburón?", want: ["Selachii"] },
      { q: "Qual é a capital do Japão?", want: ["Japão"] },
    ];
    const misses: string[] = [];
    for (const s of SAMPLE) {
      const top = search(s.q)[0]?.title;
      if (top === undefined || !s.want.includes(top)) misses.push(`${s.q} -> ${top}`);
    }
    // La única falla tolerada es la medida: «Coreia do Sul» gana a «Japão»
    // en la pregunta portuguesa por la capital de Japón.
    expect(misses).toEqual(["Qual é a capital do Japão? -> Coreia do Sul"]);
  });
});
